#!/usr/bin/env bash
# Regenerates src/SimpleSign.Brasil/IcpBrasil/Certs/IcpBrasilHomologation.pem: the ICP-Brasil
# homologation (test) hierarchy used by SERPRO and the ACs for test certificates. The ITI does not
# publish it as a bundle; this takes the keystore Demoiselle Signer ships
# (chain-icp-brasil-homolog, BKS v2, password "serprosigner"), extracts the certificates,
# drops duplicates and expired ones and writes them as PEM.
#
# These certificates are only trusted with IcpBrasilEnvironment.Homologation. One of the test
# roots reuses the exact subject of the production AC Raiz v12 with another key: certificates
# are matched by their bytes, never by name.
set -euo pipefail

url="https://raw.githubusercontent.com/demoiselle/signer/master/chain-icp-brasil-homolog/src/main/resources/cadeiasicpbrasil-HOMOLOGACAO.bks"
repo="$(cd "$(dirname "$0")/.." && pwd)"
out="$repo/src/SimpleSign.Brasil/IcpBrasil/Certs/IcpBrasilHomologation.pem"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

curl -fsSL "$url" -o "$tmp/hom.bks"
mkdir "$tmp/certs"

# BKS v2 layout: version, salt, iteration count, then entries
# (type, alias, date, chain, …) until a 0 type byte; certificates are "X.509" + DER.
python3 -I - "$tmp/hom.bks" "$tmp/certs" <<'PY'
import os, struct, sys
data = open(sys.argv[1], 'rb').read()
out = sys.argv[2]
pos = 0
def take(n):
    global pos
    chunk = data[pos:pos + n]
    pos += n
    return chunk
def i32():
    return struct.unpack('>i', take(4))[0]
def utf():
    return take(struct.unpack('>H', take(2))[0]).decode('utf-8', 'replace')
def cert():
    utf()
    return take(i32())
if i32() not in (1, 2):
    sys.exit('not a BKS keystore')
take(i32())
i32()
count = 0
while True:
    kind = take(1)[0]
    if kind == 0:
        break
    utf()
    take(8)
    chain = [cert() for _ in range(i32())]
    if kind == 1:
        chain = [cert()]
    else:
        take(i32())
    for der in chain:
        count += 1
        open(os.path.join(out, f'{count:04d}.der'), 'wb').write(der)
print(f'{count} certificates read', file=sys.stderr)
PY

now="$(date -u +%s)"
{
  echo "# ICP-Brasil homologation (test) CA certificates. NOT valid for production signatures."
  echo "# Source: Demoiselle Signer chain-icp-brasil-homolog, $url"
  echo "# Generated by scripts/update-icp-homologation.sh on $(date -u +%Y-%m-%d). Do not edit."
  for f in "$tmp"/certs/*.der; do
    fp="$(openssl x509 -inform der -in "$f" -noout -fingerprint -sha256 2>/dev/null)" || continue
    end="$(openssl x509 -inform der -in "$f" -noout -enddate | cut -d= -f2)"
    end_s="$(date -u -j -f '%b %e %T %Y %Z' "$end" +%s 2>/dev/null || date -u -d "$end" +%s)"
    [ "$end_s" -gt "$now" ] || continue
    echo "$fp|$f"
  done | LC_ALL=C sort -u -t'|' -k1,1 | while IFS='|' read -r _ f; do
    echo "# $(openssl x509 -inform der -in "$f" -noout -subject -nameopt RFC2253 | sed 's/^subject=//')"
    openssl x509 -inform der -in "$f" -outform pem
  done
} > "$out"

echo "Wrote $(grep -c 'BEGIN CERTIFICATE' "$out") certificates to $out"
