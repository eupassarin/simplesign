namespace SimpleSign.HtmlToPdf;

/// <summary>Style variant of a registered font face.</summary>
public enum FontVariant
{
    /// <summary>Upright, normal weight.</summary>
    Regular,

    /// <summary>Upright, bold weight (used for <c>font-weight</c> 600 and above).</summary>
    Bold,

    /// <summary>Italic, normal weight.</summary>
    Italic,

    /// <summary>Italic, bold weight.</summary>
    BoldItalic,
}
