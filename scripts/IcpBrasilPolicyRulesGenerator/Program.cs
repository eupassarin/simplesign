using System.Globalization;
using System.Text;
using SimpleSign.Brasil.IcpBrasil;

// Reads every PA_*.der in the directory, parses its rules with the library's own parser and writes
// the compact catalog the library embeds (the PAs themselves are ~660 KB, mostly root certificates).
if (args.Length != 1 || !Directory.Exists(args[0]))
{
    Console.Error.WriteLine("usage: dotnet run --project scripts/IcpBrasilPolicyRulesGenerator -- <directory with PA_*.der>");
    return 1;
}

static string Quote(string s) => "\"" + s.Replace("\\", "\\\\", StringComparison.Ordinal).Replace("\"", "\\\"", StringComparison.Ordinal) + "\"";
static string List(IEnumerable<string> values) => "[" + string.Join(", ", values.Select(Quote)) + "]";

var rules = Directory.GetFiles(args[0], "PA_*.der")
    .Select(f => IcpBrasilPolicyRules.Parse(File.ReadAllBytes(f)))
    .OrderBy(r => r.Oid, StringComparer.Ordinal)
    .ToList();

var sb = new StringBuilder();
sb.AppendLine("namespace SimpleSign.Brasil.IcpBrasil;");
sb.AppendLine();
sb.AppendLine("// Generated by scripts/IcpBrasilPolicyRulesGenerator from the ITI PA files (CAdES and PAdES). Do not edit.");
sb.AppendLine("internal static class IcpBrasilPolicyRulesCatalog");
sb.AppendLine("{");
sb.AppendLine("    internal static readonly IcpBrasilPolicyRules[] Rules =");
sb.AppendLine("    [");
foreach (var r in rules)
{
    string algorithms = "[" + string.Join(", ", r.SignerAlgorithms.Select(a =>
        $"new({Quote(a.Oid)}, {(a.MinKeyLength is { } k ? k.ToString(CultureInfo.InvariantCulture) : "null")})")) + "]";
    sb.AppendLine($"        new({Quote(r.Oid)},");
    sb.AppendLine($"            {List(r.TrustAnchorKeySha256)},");
    sb.AppendLine($"            {List(r.TrustAnchorSubjects)},");
    sb.AppendLine($"            {List(r.MandatedSignedAttributes)},");
    sb.AppendLine($"            {List(r.MandatedUnsignedAttributes)},");
    sb.AppendLine($"            {algorithms}),");
}

sb.AppendLine("    ];");
sb.AppendLine("}");
Console.Write(sb.ToString());
Console.Error.WriteLine($"{rules.Count} policies");
return 0;
