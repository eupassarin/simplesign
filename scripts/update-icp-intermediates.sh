#!/usr/bin/env bash
# Regenerates src/TrustFrameworks/Brazil/IcpBrasil/SimpleSign.Brazil.IcpBrasil/Certs/IcpBrasilIntermediates.pem from the ITI's
# bundle of every ICP-Brasil CA certificate. Roots (self-signed) are skipped: they are bundled
# separately and pinned. The intermediates are only chain-building help (never trust anchors);
# IcpBrasilIntermediatesTests checks that each one chains to a bundled AC Raiz.
set -euo pipefail

url="https://acraiz.icpbrasil.gov.br/credenciadas/CertificadosAC-ICP-Brasil/ACcompactado.zip"
repo="$(cd "$(dirname "$0")/.." && pwd)"
out="$repo/src/TrustFrameworks/Brazil/IcpBrasil/SimpleSign.Brazil.IcpBrasil/Certs/IcpBrasilIntermediates.pem"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

curl -fsSL "$url" -o "$tmp/ac.zip"
unzip -q "$tmp/ac.zip" -d "$tmp/ac"

{
  echo "# ICP-Brasil intermediate CA certificates, from $url"
  echo "# Generated by scripts/update-icp-intermediates.sh on $(date -u +%Y-%m-%d). Do not edit."
  find "$tmp/ac" -type f -name '*.crt' | LC_ALL=C sort | while read -r f; do
    subject="$(openssl x509 -in "$f" -noout -subject -nameopt RFC2253 2>/dev/null || true)"
    issuer="$(openssl x509 -in "$f" -noout -issuer -nameopt RFC2253 2>/dev/null || true)"
    if [ -z "$subject" ] || [ "${subject#subject=}" = "${issuer#issuer=}" ]; then
      continue
    fi
    echo "# $(basename "$f")"
    tr -d '\r' < "$f"
    echo
  done
} > "$out"

echo "Wrote $(grep -c 'BEGIN CERTIFICATE' "$out") certificates to $out"
