using System.Globalization;
using System.Text;
using SimpleSign.Brasil.IcpBrasil;

// Reads every PA_*.der (CAdES/PAdES) and PA_*.xml (XAdES) in the directories, parses their rules
// with the library's own parsers and writes the compact catalog the library embeds (the PAs
// themselves are over 1 MB, mostly root certificates).
if (args.Length == 0 || args.Any(a => !Directory.Exists(a)))
{
    Console.Error.WriteLine("usage: dotnet run --project scripts/IcpBrasilPolicyRulesGenerator -- <directory with PA_*.der> [<directory with PA_*.xml>]");
    return 1;
}

static string Quote(string s) => "\"" + s.Replace("\\", "\\\\", StringComparison.Ordinal).Replace("\"", "\\\"", StringComparison.Ordinal) + "\"";
static string List(IEnumerable<string> values) => "[" + string.Join(", ", values.Select(Quote)) + "]";

var rules = args.SelectMany(dir => Directory.GetFiles(dir, "PA_*.der").Select(f => IcpBrasilPolicyRules.Parse(File.ReadAllBytes(f)))
        .Concat(Directory.GetFiles(dir, "PA_*.xml").Select(f => IcpBrasilPolicyRules.ParseXml(File.ReadAllBytes(f)))))
    .GroupBy(r => r.Oid, StringComparer.Ordinal)
    .Select(g => g.First())
    .OrderBy(r => r.Oid, StringComparer.Ordinal)
    .ToList();

var sb = new StringBuilder();
sb.AppendLine("namespace SimpleSign.Brasil.IcpBrasil;");
sb.AppendLine();
sb.AppendLine("// Generated by scripts/IcpBrasilPolicyRulesGenerator from the ITI PA files (CAdES, PAdES and XAdES). Do not edit.");
sb.AppendLine("internal static class IcpBrasilPolicyRulesCatalog");
sb.AppendLine("{");
sb.AppendLine("    internal static readonly IcpBrasilPolicyRules[] Rules =");
sb.AppendLine("    [");
foreach (var r in rules)
{
    string algorithms = "[" + string.Join(", ", r.SignerAlgorithms.Select(a =>
        $"new({Quote(a.Oid)}, {(a.MinKeyLength is { } k ? k.ToString(CultureInfo.InvariantCulture) : "null")})")) + "]";
    sb.AppendLine($"        new({Quote(r.Oid)},");
    sb.AppendLine($"            {List(r.TrustAnchorKeySha256)},");
    sb.AppendLine($"            {List(r.TrustAnchorSubjects)},");
    sb.AppendLine($"            {List(r.MandatedSignedAttributes)},");
    sb.AppendLine($"            {List(r.MandatedUnsignedAttributes)},");
    sb.AppendLine($"            {algorithms}),");
}

sb.AppendLine("    ];");
sb.AppendLine("}");
Console.Write(sb.ToString());
Console.Error.WriteLine($"{rules.Count} policies");
return 0;
